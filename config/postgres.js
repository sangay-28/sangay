const { Pool } = require('pg');
const { CLUB_NAMES } = require('../utils/clubs');
const { CLUB_EVENTS } = require('../utils/club-events');

async function initializePostgresDatabase(connectionString) {
  if (!connectionString) {
    throw new Error(
      'DATABASE_URL is empty. In pgAdmin, create a PostgreSQL login role and the sherubtse_clubs database, then set DATABASE_URL in .env (see .env.example).',
    );
  }
  const pool = new Pool({
    connectionString,
    ssl: process.env.PGSSL === 'true' ? { rejectUnauthorized: false } : undefined,
  });
  pool.dialect = 'postgres';
  pool.on('error', (error) => console.error('Unexpected PostgreSQL pool error:', error.message));

  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS clubs (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL UNIQUE
      );
      CREATE TABLE IF NOT EXISTS accounts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name TEXT NOT NULL,
        email TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL CHECK (role IN ('member','leader')),
        club TEXT,
        club_id INTEGER REFERENCES clubs(id),
        course TEXT,
        year INTEGER CHECK (year IS NULL OR year BETWEEN 1 AND 4),
        active SMALLINT NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE UNIQUE INDEX IF NOT EXISTS idx_accounts_email_ci ON accounts (LOWER(email));
      CREATE TABLE IF NOT EXISTS otp_challenges (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL,
        role TEXT NOT NULL CHECK (role IN ('member','leader','admin')),
        purpose TEXT NOT NULL CHECK (purpose IN ('login','signup')),
        code_hash TEXT NOT NULL,
        metadata TEXT,
        expires_at BIGINT NOT NULL,
        attempts INTEGER NOT NULL DEFAULT 0,
        consumed SMALLINT NOT NULL DEFAULT 0 CHECK (consumed IN (0,1)),
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE INDEX IF NOT EXISTS idx_otp_challenges_email ON otp_challenges (email, purpose, created_at DESC);
      CREATE TABLE IF NOT EXISTS contact_messages (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL,
        email TEXT NOT NULL,
        subject TEXT NOT NULL,
        message TEXT NOT NULL,
        consent SMALLINT NOT NULL DEFAULT 1 CHECK (consent IN (0,1)),
        status TEXT NOT NULL DEFAULT 'new',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE TABLE IF NOT EXISTS membership_applications (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        full_name TEXT NOT NULL,
        course TEXT NOT NULL,
        year INTEGER NOT NULL CHECK (year BETWEEN 1 AND 4),
        club TEXT NOT NULL,
        club_id INTEGER REFERENCES clubs(id),
        email TEXT,
        account_id INTEGER REFERENCES accounts(id) ON DELETE SET NULL,
        consent SMALLINT NOT NULL DEFAULT 1 CHECK (consent IN (0,1)),
        status TEXT NOT NULL DEFAULT 'pending',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
      );
      CREATE TABLE IF NOT EXISTS club_events (
        event_id TEXT PRIMARY KEY,
        title TEXT NOT NULL,
        category TEXT NOT NULL,
        date TEXT NOT NULL,
        status TEXT NOT NULL,
        club TEXT NOT NULL,
        club_id INTEGER REFERENCES clubs(id)
      );
      CREATE TABLE IF NOT EXISTS event_registrations (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        first_name TEXT NOT NULL,
        last_name TEXT NOT NULL,
        student_id TEXT NOT NULL,
        email TEXT NOT NULL,
        phone TEXT,
        department TEXT NOT NULL,
        year TEXT NOT NULL,
        event_id TEXT NOT NULL REFERENCES club_events(event_id),
        club TEXT,
        club_id INTEGER REFERENCES clubs(id),
        account_id INTEGER REFERENCES accounts(id) ON DELETE SET NULL,
        role TEXT,
        message TEXT,
        consent SMALLINT NOT NULL DEFAULT 1 CHECK (consent IN (0,1)),
        status TEXT NOT NULL DEFAULT 'registered',
        created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
        UNIQUE (student_id,event_id)
      );
    `);

    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      for (const club of CLUB_NAMES) {
        await client.query('INSERT INTO clubs (name) VALUES ($1) ON CONFLICT (name) DO NOTHING', [
          club,
        ]);
      }
      for (const [eventId, event] of Object.entries(CLUB_EVENTS)) {
        const club = await client.query('SELECT id FROM clubs WHERE name=$1', [event.club]);
        await client.query(
          `INSERT INTO club_events (event_id,title,category,date,status,club,club_id)
          VALUES ($1,$2,$3,$4,$5,$6,$7) ON CONFLICT (event_id) DO NOTHING`,
          [
            eventId,
            event.title,
            event.category,
            event.date,
            event.status,
            event.club,
            club.rows[0].id,
          ],
        );
      }
      await client.query(
        'UPDATE club_events SET club_id=clubs.id FROM clubs WHERE club_events.club=clubs.name AND club_events.club_id IS NULL',
      );
      for (const table of ['accounts', 'membership_applications', 'event_registrations']) {
        await client.query(
          `UPDATE ${table} SET club_id=clubs.id FROM clubs WHERE ${table}.club=clubs.name AND ${table}.club_id IS NULL`,
        );
      }
      await client.query('COMMIT');
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
    await pool.query('SELECT 1');
    return pool;
  } catch (error) {
    await pool.end();
    throw error;
  }
}

module.exports = { initializePostgresDatabase };
